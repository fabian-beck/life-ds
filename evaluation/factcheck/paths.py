#!/usr/bin/env python3
"""Where this tool reads from and writes to.

The generation scripts are not a package — they resolve their own imports by
putting ``scripts/`` on ``sys.path`` — so every module here that needs one of
them imports this first and then imports the script module by its bare name.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPTS_DIR = REPO_ROOT / "scripts"
DATA_DIR = REPO_ROOT / "data"
PEOPLE_DIR = DATA_DIR / "people"
PERSONS_REGISTER = DATA_DIR / "persons.json"

EVALUATION_DIR = REPO_ROOT / "evaluation"
APP_DIR = EVALUATION_DIR / "app"

# Everything generated by the four stages. Ignored by git: a bundle carries
# quoted source text and a result file carries an evaluator's judgments, and
# neither belongs in the repository that the stories are generated from.
OUT_DIR = EVALUATION_DIR / "out"
FACTS_DIR = OUT_DIR / "facts"
BUNDLES_DIR = OUT_DIR / "bundles"
RESULTS_DIR = OUT_DIR / "results"
REPORTS_DIR = OUT_DIR / "reports"

if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))


def cache_dir(person_id: str) -> Path:
    """The Wikipedia materials the generation pipeline cached for a person."""
    return PEOPLE_DIR / person_id / "_cache"


def ensure_out_dirs() -> None:
    """Create the output tree on first use."""
    for directory in (FACTS_DIR, BUNDLES_DIR, RESULTS_DIR, REPORTS_DIR):
        directory.mkdir(parents=True, exist_ok=True)
